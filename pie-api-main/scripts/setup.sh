#!/usr/bin/env bash
# First-run setup for a new PIE-API deployment.
#
# Generates a `.env` file with unique, randomly-generated secrets so a
# professor/examiner standing up their own instance never has to pick or
# type a password/JWT secret themselves, and the TLS certificates (see
# generate-certs.sh). Safe to re-run: an existing `.env` or certificate is
# left untouched.
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT_DIR="$(dirname "$SCRIPT_DIR")"
ENV_FILE="$ROOT_DIR/.env"

if ! command -v openssl >/dev/null 2>&1; then
  echo "Error: openssl is required to generate secrets but was not found." >&2
  echo "Install it (e.g. 'apt install openssl' or 'brew install openssl') and re-run this script." >&2
  exit 1
fi

if [[ -f "$ROOT_DIR/certs/server.crt" && -f "$ROOT_DIR/certs/phone-ca.key" ]]; then
  echo "TLS certificates already exist in $ROOT_DIR/certs — leaving them untouched."
  echo "Run scripts/generate-certs.sh to re-issue the server certificate."
else
  "$SCRIPT_DIR/generate-certs.sh"
fi
echo

# The API's address as teachers' browsers reach it, compiled into the
# dashboard: this machine's main IPv4 address (the one its default route
# uses). Check it in .env; edit it and rebuild if it is not the right one.
default_api_url() {
  local ip=""
  ip="$(ip -4 route get 1.1.1.1 2>/dev/null | awk '{for (i = 1; i < NF; i++) if ($i == "src") { print $(i + 1); exit }}')" || true
  if [[ -z "$ip" ]] && hostname -I >/dev/null 2>&1; then
    ip="$(hostname -I | awk '{print $1}')"
  fi
  echo "https://${ip:-localhost}:8000"
}

if [[ -f "$ENV_FILE" ]]; then
  # Settings added after a deployment's .env was first generated: append the
  # missing ones, never touching the existing values.
  if ! grep -q '^DEVICE_PSK_WRAP_KEY=' "$ENV_FILE"; then
    printf '\n# Wraps the exam devices TLS pre-shared keys (README.md, "Device TLS-PSK")\nDEVICE_PSK_WRAP_KEY=%s\n' \
      "$(openssl rand -hex 32)" >> "$ENV_FILE"
    echo "Added DEVICE_PSK_WRAP_KEY to the existing $ENV_FILE."
  fi
  if ! grep -q '^PIE_API_URL=' "$ENV_FILE"; then
    PIE_API_URL="$(default_api_url)"
    printf '\n# The API address compiled into the dashboard (rebuild after changing it)\nPIE_API_URL=%s\n' \
      "$PIE_API_URL" >> "$ENV_FILE"
    echo "Added PIE_API_URL=$PIE_API_URL to the existing $ENV_FILE; check it is the address teachers' browsers use."
  fi
  echo "A .env file already exists at $ENV_FILE — leaving its other values untouched."
  echo "Delete it first if you want this script to generate a fresh one."
  exit 0
fi

echo "Generating secrets for a new PIE-API deployment..."

JWT_SECRET_KEY="$(openssl rand -hex 32)"
MYSQL_ROOT_PASSWORD="$(openssl rand -hex 16)"
MYSQL_PASSWORD="$(openssl rand -hex 16)"
DEVICE_PSK_WRAP_KEY="$(openssl rand -hex 32)"
PIE_API_URL="$(default_api_url)"

cat > "$ENV_FILE" <<EOF
# Generated by scripts/setup.sh on $(date -u +"%Y-%m-%dT%H:%M:%SZ").
# This file contains secrets for THIS deployment only — never commit it
# or share it. Re-running docker compose is fine; re-running setup.sh
# will not overwrite it.

# FastAPI
APP_PORT=8000
JWT_SECRET_KEY=${JWT_SECRET_KEY}
JWT_ALGORITHM=HS256
# Wraps the exam devices' TLS pre-shared keys (README.md, "Device TLS-PSK")
DEVICE_PSK_WRAP_KEY=${DEVICE_PSK_WRAP_KEY}
# The API address compiled into the dashboard (rebuild after changing it)
PIE_API_URL=${PIE_API_URL}

# MySQL Database
MYSQL_ROOT_PASSWORD=${MYSQL_ROOT_PASSWORD}
MYSQL_USER=pie
MYSQL_PASSWORD=${MYSQL_PASSWORD}
MYSQL_DB=pie_api_db
MYSQL_HOST=db
MYSQL_PORT=3306
DATABASE_URL=mysql+pymysql://pie:${MYSQL_PASSWORD}@db:3306/pie_api_db

# Redis
REDIS_HOST=redis
REDIS_PORT=6379
REDIS_URL=redis://redis:6379

# Celery
CELERY_BROKER_URL=redis://redis:6379/0
CELERY_RESULT_BACKEND=redis://redis:6379/0

# ClamAV
CLAMAV_HOST=clamav
CLAMAV_PORT=3310

# ElasticSearch
ELASTICSEARCH_HOST=elasticsearch
ELASTICSEARCH_PORT=9200
ELASTICSEARCH_URL=http://elasticsearch:9200

# Log Settings
LOG_RETENTION_DAYS=7
LOG_MAX_STREAM_LENGTH=1000
EOF

chmod 600 "$ENV_FILE"

echo "Created $ENV_FILE with freshly generated secrets."
echo "The dashboard will use the API at $PIE_API_URL (PIE_API_URL in .env); change it there if teachers reach this machine at another address."
echo "You can now run: docker compose up --build"
